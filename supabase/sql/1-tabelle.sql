-- FAMIGLIA - tabelle, sicurezza, copia notturna e promemoria (progetto bybshobzuopcfnhrjpvg)
-- Più famiglie separate: chi si registra crea una famiglia e ne è il Capofamiglia; gli altri entrano con un suo invito.
-- Si può eseguire da PannelloApp (Supabase › Esegui 1-tabelle.sql) o dall'SQL Editor. Si può rieseguire senza danni.
-- Aggiorna anche le tabelle della prima versione: account e impegni già presenti finiscono in "La mia famiglia".

-- Famiglie. capo_id è l'account del Capofamiglia (può passare il ruolo a un altro adulto con account).
create table if not exists public.famiglia_famiglie (
  id bigint generated by default as identity primary key,
  nome text not null,
  capo_id bigint,
  creato timestamptz not null default now()
);

-- Utenti (chi ha un account). Ogni account appartiene a una sola famiglia.
create table if not exists public.famiglia_utenti (
  id bigint generated by default as identity primary key,
  famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade,
  username text unique not null,
  pass text not null,
  errori int not null default 0,
  bloccato_fino timestamptz,
  creato timestamptz not null default now(),
  ultimo_accesso timestamptz
);

-- Membri: tutti quelli che possono avere impegni (mamma, papà, figli, "Famiglia", il cane...).
-- utente_id è vuoto per chi non ha un account. tipo: adulto, bambino, gruppo.
create table if not exists public.famiglia_membri (
  id bigint generated by default as identity primary key,
  famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade,
  nome text not null,
  colore text not null default '#1F6F5C',
  tipo text not null default 'adulto' check (tipo in ('adulto','bambino','gruppo')),
  utente_id bigint unique references public.famiglia_utenti(id) on delete set null,
  ordine int not null default 0,
  archiviato boolean not null default false,
  creato timestamptz not null default now()
);

-- Impegni. Orari in ora italiana (giorno + "HH:MM"); senza ora = tutto il giorno.
-- visibilita: condiviso (tutti vedono tutto), occupato (gli altri vedono solo l'orario), privato (solo chi l'ha creato).
-- ripeti: '' (mai), giorno, settimana, mese, anno. giorni_sett: 1=lunedì ... 7=domenica. eccezioni: giorni saltati.
-- da_accompagnare: se vero, serve un adulto che accompagni (accompagna = quel membro, vuoto = ancora nessuno).
create table if not exists public.famiglia_impegni (
  id uuid primary key,
  famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade,
  titolo text not null,
  giorno date not null,
  giorno_fine date,
  ora_inizio text,
  ora_fine text,
  luogo text not null default '',
  note text not null default '',
  visibilita text not null default 'condiviso' check (visibilita in ('condiviso','occupato','privato')),
  creato_da bigint not null references public.famiglia_utenti(id) on delete cascade,
  membri bigint[] not null default '{}',
  da_accompagnare boolean not null default false,
  accompagna bigint references public.famiglia_membri(id) on delete set null,
  ripeti text not null default '' check (ripeti in ('','giorno','settimana','mese','anno')),
  giorni_sett int[] not null default '{}',
  fino_a date,
  eccezioni date[] not null default '{}',
  promemoria_min int,
  creato timestamptz not null default now(),
  aggiornato timestamptz not null default now(),
  cancellato boolean not null default false
);

-- Accessi attivi (uno per telefono)
create table if not exists public.famiglia_accessi_attivi (
  h text primary key,
  user_id bigint not null references public.famiglia_utenti(id) on delete cascade,
  creato timestamptz not null default now(),
  ultimo_uso timestamptz not null default now()
);

-- Link di invito (7 giorni) e per una nuova password (24 ore), una volta sola
create table if not exists public.famiglia_link (
  h text primary key,
  tipo text not null check (tipo in ('invito','password')),
  famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade,
  user_id bigint references public.famiglia_utenti(id) on delete cascade,
  membro_id bigint references public.famiglia_membri(id) on delete cascade,
  creato_da bigint references public.famiglia_utenti(id) on delete set null,
  scade timestamptz not null,
  usato timestamptz
);

-- Tentativi falliti (protezione contro chi prova password a caso o crea troppe famiglie)
create table if not exists public.famiglia_tentativi_falliti (id bigserial primary key, at timestamptz not null default now(), tipo text);

-- Notifiche push: un'iscrizione per telefono, e i promemoria già inviati (per non mandarli due volte)
create table if not exists public.famiglia_push (
  endpoint text primary key,
  user_id bigint not null references public.famiglia_utenti(id) on delete cascade,
  sub jsonb not null,
  creato timestamptz not null default now()
);
create table if not exists public.famiglia_promemoria_inviati (k text primary key, at timestamptz not null default now());

-- Copie di sicurezza notturne (famiglie, membri e impegni; non le password)
create table if not exists public.famiglia_copie_notturne (
  id bigserial primary key,
  at timestamptz not null default now(),
  data jsonb not null
);

-- Impostazioni del server. "cron" è il codice con cui il giro dei promemoria si fa riconoscere dalla funzione:
-- si genera da solo la prima volta e non va copiato da nessuna parte.
create table if not exists public.famiglia_config (chiave text primary key, valore text not null);
insert into public.famiglia_config (chiave, valore)
  values ('cron', replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''))
  on conflict (chiave) do nothing;

-- ---------- Aggiornamento dalla prima versione (tabelle create prima delle famiglie)
alter table public.famiglia_impegni add column if not exists da_accompagnare boolean not null default false;
alter table public.famiglia_utenti  add column if not exists famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade;
alter table public.famiglia_membri  add column if not exists famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade;
alter table public.famiglia_impegni add column if not exists famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade;
alter table public.famiglia_link    add column if not exists famiglia_id bigint references public.famiglia_famiglie(id) on delete cascade;
do $$
declare fid bigint; capo bigint;
begin
  -- Dati già presenti senza famiglia: tutti in "La mia famiglia", Capofamiglia il primo account registrato
  if exists (select 1 from public.famiglia_utenti where famiglia_id is null)
     or exists (select 1 from public.famiglia_membri where famiglia_id is null)
     or exists (select 1 from public.famiglia_impegni where famiglia_id is null)
     or exists (select 1 from public.famiglia_link where famiglia_id is null) then
    select id into capo from public.famiglia_utenti order by id limit 1;
    insert into public.famiglia_famiglie (nome, capo_id) values ('La mia famiglia', capo) returning id into fid;
    update public.famiglia_utenti  set famiglia_id = fid where famiglia_id is null;
    update public.famiglia_membri  set famiglia_id = fid where famiglia_id is null;
    update public.famiglia_impegni set famiglia_id = fid where famiglia_id is null;
    update public.famiglia_link    set famiglia_id = fid where famiglia_id is null;
  end if;
end $$;
alter table public.famiglia_utenti  alter column famiglia_id set not null;
alter table public.famiglia_membri  alter column famiglia_id set not null;
alter table public.famiglia_impegni alter column famiglia_id set not null;
alter table public.famiglia_link    alter column famiglia_id set not null;
alter table public.famiglia_utenti  drop column if exists admin; -- c'era nella prima versione, ora c'è il Capofamiglia

-- Indici (dopo l'aggiornamento, quando le colonne ci sono di sicuro)
create index if not exists famiglia_utenti_famiglia on public.famiglia_utenti (famiglia_id);
create index if not exists famiglia_membri_famiglia on public.famiglia_membri (famiglia_id);
drop index if exists public.famiglia_impegni_giorno;
create index if not exists famiglia_impegni_famiglia_giorno on public.famiglia_impegni (famiglia_id, giorno);

-- Sicurezza: le tabelle si leggono e scrivono solo dalla funzione "api"
do $$
declare t text;
begin
  foreach t in array array['famiglia_famiglie','famiglia_utenti','famiglia_membri','famiglia_impegni','famiglia_accessi_attivi','famiglia_link',
                           'famiglia_tentativi_falliti','famiglia_push','famiglia_promemoria_inviati','famiglia_copie_notturne','famiglia_config'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant all on public.%I to service_role', t);
  end loop;
end $$;
grant usage on schema public to service_role;
grant usage, select on all sequences in schema public to service_role;

create extension if not exists pg_cron;
create extension if not exists pg_net;

-- Ogni notte alle 2:30 UTC: copia di famiglie, membri e impegni (tenuta 30 giorni) e pulizia
select cron.unschedule('famiglia-copia-notturna') where exists (select 1 from cron.job where jobname = 'famiglia-copia-notturna');
select cron.schedule('famiglia-copia-notturna', '30 2 * * *', $$
  insert into public.famiglia_copie_notturne (data) select jsonb_build_object(
    'famiglie', (select coalesce(jsonb_agg(to_jsonb(f)), '[]'::jsonb) from public.famiglia_famiglie f),
    'membri', (select coalesce(jsonb_agg(to_jsonb(m)), '[]'::jsonb) from public.famiglia_membri m),
    'impegni', (select coalesce(jsonb_agg(to_jsonb(i)), '[]'::jsonb) from public.famiglia_impegni i));
  delete from public.famiglia_copie_notturne where at < now() - interval '30 days';
  delete from public.famiglia_accessi_attivi where ultimo_uso < now() - interval '400 days';
  delete from public.famiglia_link where scade < now() - interval '30 days';
  delete from public.famiglia_tentativi_falliti where at < now() - interval '1 day';
  delete from public.famiglia_promemoria_inviati where at < now() - interval '3 days';
  delete from public.famiglia_impegni where cancellato and aggiornato < now() - interval '60 days';
$$);

-- Ogni minuto: la funzione controlla se c'è un promemoria da mandare (con il codice di famiglia_config)
select cron.unschedule('famiglia-promemoria') where exists (select 1 from cron.job where jobname = 'famiglia-promemoria');
select cron.schedule('famiglia-promemoria', '* * * * *', $$
  select net.http_post(
    url := 'https://bybshobzuopcfnhrjpvg.supabase.co/functions/v1/api/cron',
    headers := jsonb_build_object('x-cron', (select valore from public.famiglia_config where chiave = 'cron'), 'content-type', 'application/json'),
    body := '{}'::jsonb
  )
$$);

